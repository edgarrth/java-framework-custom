#!/usr/bin/env python3
"""Inventory the bytes verified by a build; never compile or promote artifacts."""
import argparse
import json
import os
import shutil
from pathlib import Path

from manifest import canonical_hash, read_json, safe_file, sha256, validate


def complete(data, bundle):
    """Called only after every build gate has succeeded, using actual retained evidence."""
    gate_files = {"tests": "verify.log", "quality": "verify.log", "mutation": "mutation.log",
                  "encapsulation": "encapsulation.log", "sbom": "bom.json", "scan": "scan.json"}
    if data["kind"] == "service":
        gate_files.update(contracts="contracts.log", chart="chart.log")
    elif "native" in data["parameters"]:
        gate_files["native"] = "native.json"

    def evidence(name):
        path = "reports/" + name
        content = safe_file(bundle, path).read_bytes()
        if not content.strip():
            raise ValueError(f"Empty build evidence: {path}")
        return {"path": path, "sha256": sha256(content)}

    data["gates"] = [{"name": name, "result": "passed", "evidence": evidence(file)}
                     for name, file in sorted(gate_files.items())]
    data["sbom"] = evidence("bom.json")
    if data["kind"] == "maven-library":
        subjects = [{"name": file["path"], "digest": {"sha256": file["sha256"]}} for file in data["artifacts"]["maven"]]
    else:
        subjects = [{"name": data["artifacts"][key]["repository" if key == "image" else "oci"],
                     "digest": {"sha256": data["artifacts"][key]["digest"].removeprefix("sha256:")}}
                    for key in ("image", "chart")]
    provenance = {"_type": "https://in-toto.io/Statement/v1", "subject": subjects,
                  "predicateType": "https://slsa.dev/provenance/v1", "predicate": {
                      "buildDefinition": {"buildType": "https://github.com/axiz/axiz-workflows/build/v2",
                                          "externalParameters": data["parameters"], "resolvedDependencies": [{
                                              "uri": "git+https://github.com/" + data["source"]["repository"],
                                              "digest": {"gitCommit": data["source"]["sha"]}}]},
                      "runDetails": {"builder": {"id": "https://github.com/axiz/axiz-workflows/" + data["build"]["workflow"]["path"] + "@" + data["build"]["workflow"]["ref"],
                                                 "version": {"gitCommit": data["build"]["workflow"]["sha"]}}, "metadata": {
                          "invocationId": f"https://github.com/{data['source']['repository']}/actions/runs/{data['build']['run_id']}/attempts/{data['build']['run_attempt']}"}}}}
    candidate = data.get("dependencies", {}).get("axiz_build")
    if candidate:
        provenance["predicate"]["buildDefinition"]["resolvedDependencies"].append({
            "uri": f"https://github.com/{candidate['repository']}/actions/runs/{candidate['run_id']}/attempts/{candidate['run_attempt']}",
            "digest": {"sha256": candidate["manifest_sha256"]}})
    (bundle / "reports/provenance.intoto.json").write_text(json.dumps(provenance, sort_keys=True) + "\n")
    data["provenance"] = evidence("provenance.intoto.json")


def inventory(root, version):
    entries = []
    # Repository metadata is generated by Nexus, never copied over the repository's existing version index.
    for path in sorted(root.rglob("*")):
        if not path.is_file() and not path.is_symlink():
            continue
        relative = path.relative_to(root).as_posix()
        safe_file(root, relative)
        if path.name.startswith("maven-metadata.xml") or path.name.startswith("maven-metadata-staging.xml"):
            path.unlink()
            continue
        parts = relative.split("/")
        if len(parts) < 4 or parts[-2] != version:
            raise ValueError(f"Unexpected file in Maven staging: {relative}")
        artifact = parts[-3]
        prefix = artifact + "-" + version
        suffix = parts[-1].removeprefix(prefix)
        if not parts[-1].startswith(prefix) or not suffix or suffix[0] not in ".-":
            raise ValueError(f"File does not match its Maven coordinate: {relative}")
        classifier = None
        if suffix.startswith("-"):
            classifier, separator, extension = suffix[1:].partition(".")
            if not separator:
                raise ValueError(f"Artifact without extension: {relative}")
        else:
            extension = suffix[1:]
        entry = {"groupId": ".".join(parts[:-3]), "artifactId": artifact, "version": version,
                 "extension": extension, "path": relative, "sha256": sha256(path.read_bytes())}
        if classifier:
            entry["classifier"] = classifier
        entries.append(entry)
    if not entries:
        raise ValueError("Maven staging contains no product files")
    (root / "SHA256SUMS").write_text("".join(item["sha256"] + "  " + item["path"] + "\n" for item in entries))
    return entries


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata", type=Path, required=True)
    parser.add_argument("--bundle", type=Path, required=True)
    parser.add_argument("--staging", type=Path)
    parser.add_argument("--reports", type=Path, required=True)
    parser.add_argument("--complete", action="store_true", help="Record actual successful gate evidence and SLSA provenance")
    args = parser.parse_args()
    data = read_json(args.metadata)
    args.bundle.mkdir(parents=True, exist_ok=False)
    shutil.copytree(args.reports, args.bundle / "reports")
    if data["kind"] == "maven-library":
        if args.staging is None:
            parser.error("maven-library requires --staging")
        shutil.copytree(args.staging, args.bundle / "maven")
        data["artifacts"] = {"maven": inventory(args.bundle / "maven", data["version"])}
    if args.complete:
        complete(data, args.bundle)
    data["parameters_sha256"] = canonical_hash(data["parameters"])
    validate(data, args.bundle)
    import rfc8785
    output = args.bundle / "build-manifest.json"
    output.write_bytes(rfc8785.dumps(data))
    digest = sha256(output.read_bytes())
    print(digest)
    if "GITHUB_OUTPUT" in os.environ:
        with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as stream:
            stream.write("manifest-sha256=" + digest + "\n")


if __name__ == "__main__":
    main()
