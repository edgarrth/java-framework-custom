package pe.axiz.initializr.service;

import io.micrometer.core.instrument.Counter;
import io.micrometer.core.instrument.MeterRegistry;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;
import pe.axiz.codegen.GenerationException;
import pe.axiz.codegen.ProjectGenerator;
import pe.axiz.codegen.RequestValidator;
import pe.axiz.codegen.model.Catalog;
import pe.axiz.codegen.model.ProjectRequest;
import pe.axiz.codegen.openapi.LintFinding;
import pe.axiz.codegen.openapi.OpenApiDocument;
import pe.axiz.codegen.openapi.OpenApiLinter;
import pe.axiz.codegen.output.GeneratedProject;
import pe.axiz.core.audit.Auditable;

/**
 * Validates and generates projects. Generation happens in memory (no temporary directories, no
 * paths derived from user data); every generation is audited and counted by archetype and style.
 */
@Service
public class GenerationService {

  private static final Logger log = LoggerFactory.getLogger(GenerationService.class);

  private final ProjectGenerator generator;
  private final MeterRegistry meters;

  public GenerationService(MeterRegistry meters) {
    this(ProjectGenerator.withDefaults(), meters);
  }

  GenerationService(ProjectGenerator generator, MeterRegistry meters) {
    this.generator = generator;
    this.meters = meters;
  }

  public Catalog catalog() {
    return generator.catalog();
  }

  public RequestValidator.Result validate(ProjectRequest request) {
    return generator.validate(request);
  }

  public List<LintFinding> lint(String contract) {
    return OpenApiLinter.lint(OpenApiDocument.parse(contract));
  }

  /**
   * Generates a project.
   *
   * @throws GenerationException with every problem when the request is not valid
   */
  @Auditable(action = "generate", resource = "project", captureArguments = false)
  public GeneratedProject generate(ProjectRequest request) {
    try {
      GeneratedProject project = generator.generate(request);
      count(request, "success");
      log.info(
          "generated {} ({} / {} / {}) with {} files",
          request.name(),
          request.archetype(),
          request.framework().id(),
          request.stack().id(),
          project.files().size());
      return project;
    } catch (GenerationException e) {
      count(request, "rejected");
      throw e;
    }
  }

  private void count(ProjectRequest request, String outcome) {
    Counter.builder("axiz.initializr.generations")
        .description("Projects generated by the initializr")
        .tag("archetype", request.archetype())
        .tag("framework", request.framework().id())
        .tag("stack", request.stack().id())
        .tag("outcome", outcome)
        .register(meters)
        .increment();
  }
}
