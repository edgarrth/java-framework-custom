#!/usr/bin/env python3
"""Generates the reference pages of the site from a checkout of axiz-framework (and, optionally,
the help of the axiz CLI), so the documentation of each version matches the code of that version.

    python3 scripts/sync_reference.py --framework ../axiz-framework [--cli-help cli-help.txt]

Writes (and overwrites) only generated files, all marked with GENERATED:
    docs/capacidades/index.md, docs/capacidades/<capability>.md
    docs/arquetipos/catalogo.md
    docs/index.md, docs/<adr>.md
    docs/migracion/implementacion-2.md
    docs/referencia/index.md, docs/referencia/<layer>/<module>.md
    docs/herramientas/cli-referencia.md          (with --cli-help)
"""
import argparse
import html
import os
import re
import shutil
import sys

import yaml

GENERATED = '<!-- GENERATED by scripts/sync_reference.py from axiz-framework: do not edit -->\n'
STORE_LABELS = {
    'aurora': 'Aurora en servlet (JDBC/JPA)',
    'r2dbc': 'Aurora en reactivo (R2DBC)',
    'dynamodb': 'DynamoDB',
}
LAYERS = [
    ('platform', 'Plataforma: parents y BOMs'),
    ('core', 'Capa 1: core (Java puro)'),
    ('adapters', 'Capa 2: adaptadores tecnológicos'),
    ('kits', 'Capa 2: kits de persistencia'),
    ('spring', 'Capa 3: Spring Boot'),
    ('structures', 'Capa 4: estructuras'),
    ('extensions', 'Capa 4: extensiones'),
    ('codegen', 'Generación'),
    ('quality', 'Calidad'),
]


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(GENERATED + text.rstrip() + '\n')


def module_readmes(framework):
    """{layer: {module: README text}} for every module that has a README."""
    out = {}
    for layer, _ in LAYERS:
        root = os.path.join(framework, layer)
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = sorted(d for d in dirnames if d not in ('target', 'src', 'node_modules'))
            if 'README.md' in filenames and 'pom.xml' in filenames:
                text = open(os.path.join(dirpath, 'README.md'), encoding='utf-8').read()
                text = text.replace('<!-- generated -->\n', '')
                out.setdefault(layer, {})[os.path.basename(dirpath)] = text
    return out


def core_dependencies(framework, starter):
    """axiz core modules the autoconfigure module of a starter depends on."""
    autoconfigure = starter.replace('-starter', '-autoconfigure')
    pom = os.path.join(framework, 'spring', autoconfigure, 'pom.xml')
    if not os.path.exists(pom):
        return autoconfigure, []
    text = open(pom, encoding='utf-8').read()
    return autoconfigure, sorted(set(re.findall(r'<artifactId>(axiz-core-[\w-]+)</artifactId>', text)))


def table(rows, header):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    for r in rows:
        lines.append('| ' + ' | '.join(str(c).replace('|', '\\|') for c in r) + ' |')
    return '\n'.join(lines)


def capabilities(framework, out, modules):
    path = os.path.join(framework, 'codegen/axiz-archetypes/src/main/resources/axiz/archetypes/capabilities.yaml')
    caps = yaml.safe_load(open(path, encoding='utf-8'))['capabilities']
    archetypes = yaml.safe_load(open(path.replace('capabilities.yaml', 'catalog.yaml'), encoding='utf-8'))['archetypes']
    included = {}
    for a in archetypes:
        for s in a.get('starters') or []:
            included.setdefault(s, []).append(a['name'])
    rows = []
    for c in caps:
        name = c['name']
        description = html.escape(c.get('description', ''), quote=False)
        rows.append([f'[`{name}`]({name}.md)', description,
                     ', '.join(included.get(name, [])) or '–'])
        autoconfigure, core = core_dependencies(framework, c['starter'])
        parts = [f'# {name}\n', description + '\n']
        parts.append(f'```bash\naxiz add {name}\n```\n')
        facts = [['Starter', f'`pe.axiz:{c["starter"]}`']]
        facts.append(['Stacks del catálogo', ', '.join(c.get('stacks') or ['servlet'])])
        if c.get('requires'):
            facts.append(['Agrega también', ', '.join(f'[`{r}`]({r}.md)' for r in c['requires'])])
        if c.get('dependencies'):
            facts.append(['Dependencias', '<br>'.join(f'`{d}`' for d in c['dependencies'])])
        facts.append(['Incluida por defecto en', ', '.join(included.get(name, [])) or 'ningún arquetipo'])
        parts.append(table(facts, ['', '']) + '\n')
        if c.get('properties'):
            parts.append('## Propiedades que agrega\n')
            parts.append('Valores por defecto seguros en `application.yaml`; los valores de cada ambiente '
                         'van en el ConfigMap del servicio y los secretos en el secret store.\n')
            parts.append('```yaml\n' + yaml.safe_dump(c['properties'], sort_keys=False, allow_unicode=True,
                                                    width=120) + '```\n')
        if c.get('persistence'):
            parts.append('## Según la persistencia del servicio\n')
            for store, extra in c['persistence'].items():
                parts.append(f'### {STORE_LABELS.get(store, store)}\n')
                if not extra:
                    parts.append('Sin configuración adicional.\n')
                if extra.get('requires'):
                    parts.append('Agrega también: ' + ', '.join(f'[`{r}`]({r}.md)' for r in extra['requires']) + '\n')
                if extra.get('dependencies'):
                    parts.append('\n'.join(f'- `{d}`' for d in extra['dependencies']) + '\n')
                if extra.get('properties'):
                    parts.append('```yaml\n' + yaml.safe_dump(extra['properties'], sort_keys=False,
                                                            allow_unicode=True, width=120) + '```\n')
        if c.get('local'):
            parts.append('Perfil `local` (`application-local.yaml`):\n')
            parts.append('```yaml\n' + yaml.safe_dump(c['local'], sort_keys=False, allow_unicode=True) + '```\n')
        if c.get('configMapKeys'):
            parts.append('## Llaves del ConfigMap por ambiente\n')
            parts.append('\n'.join(f'- `{k}`' for k in c['configMapKeys']) + '\n')
        if c.get('secrets'):
            parts.append('## Secretos\n')
            parts.append('Llaves del Secret que sincroniza el ExternalSecret desde AWS Secrets Manager:\n')
            parts.append('\n'.join(f'- `{k}`' for k in c['secrets']) + '\n')
        if c.get('example'):
            parts.append('## Uso\n')
            parts.append('```java\n' + c['example'].rstrip() + '\n```\n')
        links = []
        if autoconfigure in modules.get('spring', {}):
            links.append(f'- [`{autoconfigure}`](../referencia/spring/{autoconfigure}.md)')
        for m in core:
            if m in modules.get('core', {}):
                links.append(f'- [`{m}`](../referencia/core/{m}.md)')
        if links:
            parts.append('## Módulos\n')
            parts.append('\n'.join(links) + '\n')
        write(os.path.join(out, 'capacidades', name + '.md'), '\n'.join(parts))
    intro = ('# Capacidades\n\nCatálogo de lo que `axiz add <capacidad>` (y el initializr) agrega a un '
             'servicio: starter, propiedades, llaves de ConfigMap, secretos, tablas y un ejemplo. '
             'Las capacidades marcadas en un arquetipo vienen incluidas al crear el servicio.\n\n')
    write(os.path.join(out, 'capacidades', 'index.md'),
          intro + table(rows, ['Capacidad', 'Qué aporta', 'Incluida en']) + '\n')
    return caps, archetypes


def archetype_catalog(archetypes, out):
    rows = []
    for a in archetypes:
        persistence = ', '.join(a.get('persistence') or []) or '–'
        rows.append([f'`{a["name"]}`', a['role'], ', '.join(a['structures']), ', '.join(a.get('extensions') or []), ', '.join(a['stacks']),
                     persistence, a['deployment'], 'sí' if a.get('rest') else 'no'])
    parts = ['# Catálogo de arquetipos\n',
             'La primera estructura, stack y persistencia de cada lista es el valor por defecto. Las extensiones son opcionales.\n',
             table(rows, ['Arquetipo', 'Rol', 'Estructuras', 'Extensiones', 'Stack', 'Persistencia', 'Despliegue', 'API REST']) + '\n']
    for a in archetypes:
        parts.append(f'## {a["name"]}\n')
        parts.append(a['role'] + '\n')
        if a.get('starters'):
            parts.append('Capacidades incluidas: ' + ', '.join(
                f'[`{s}`](../capacidades/{s}.md)' for s in a['starters']) + '\n')
        if a.get('properties'):
            parts.append('```yaml\n' + yaml.safe_dump(a['properties'], sort_keys=False) + '```\n')
    write(os.path.join(out, 'arquetipos', 'catalogo.md'), '\n'.join(parts))


def adrs(framework, out):
    src = os.path.join(framework, 'docs', 'adr')
    dst = os.path.join(out, 'adr')
    rows = []
    for f in sorted(os.listdir(src)):
        if not re.match(r'\d{4}-.*\.md$', f):
            continue
        text = open(os.path.join(src, f), encoding='utf-8').read()
        title = next((l[2:].strip() for l in text.splitlines() if l.startswith('# ')), f)
        status = re.search(r'(?im)^\W*(?:status|estado)\W*:?\W*(\w+)', text)
        rows.append([f'[{title}]({f})', status.group(1) if status else '–'])
        write(os.path.join(dst, f), text.replace('../migration/2.0/IMPLEMENTACION.md', '../migracion/implementacion-2.md'))
    implementation = os.path.join(framework, 'docs', 'migration', '2.0', 'IMPLEMENTACION.md')
    if os.path.isfile(implementation):
        with open(implementation, encoding='utf-8') as source:
            write(os.path.join(out, 'migracion', 'implementacion-2.md'),
                  source.read().replace('../../adr/', '../adr/'))
    write(os.path.join(dst, 'index.md'),
          '# Decisiones de arquitectura (architecture contract)\n\nDecisiones del framework, sincronizadas desde '
          '`axiz-framework/docs`. Cada servicio registra las suyas en su propio `docs`.\n\n'
          + table(rows, ['Decisión', 'Estado']) + '\n')


def reference(modules, out):
    dst = os.path.join(out, 'referencia')
    if os.path.isdir(dst):
        for layer, _ in LAYERS:
            shutil.rmtree(os.path.join(dst, layer), ignore_errors=True)
    parts = ['# Referencia de módulos\n',
             'Tipos públicos principales de cada módulo, generados desde los README del framework '
             '(en inglés, como el código).\n']
    for layer, title in LAYERS:
        mods = modules.get(layer, {})
        if not mods:
            continue
        parts.append(f'## {title}\n')
        rows = []
        for name, text in sorted(mods.items()):
            first = next((l for l in text.splitlines()[1:] if l.strip() and not l.startswith('#')), '')
            rows.append([f'[`{name}`]({layer}/{name}.md)', first.strip()])
            write(os.path.join(dst, layer, name + '.md'), text)
        parts.append(table(rows, ['Módulo', 'Descripción']) + '\n')
    write(os.path.join(dst, 'index.md'), '\n'.join(parts))


def cli_reference(help_file, out):
    text = open(help_file, encoding='utf-8').read()
    sections = re.split(r'^===== (.+)$', text, flags=re.M)
    parts = ['# Referencia de la CLI\n',
             'Salida de `--help` de cada comando de la versión publicada.\n']
    for i in range(1, len(sections), 2):
        title = sections[i].strip().replace('  ', ' ')
        body = sections[i + 1].strip('\n')
        parts.append(f'## `{title}`\n')
        parts.append('```text\n' + body + '\n```\n')
    write(os.path.join(out, 'herramientas', 'cli-referencia.md'), '\n'.join(parts))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--framework', default='../axiz-framework')
    p.add_argument('--docs', default=os.path.join(os.path.dirname(__file__), '..', 'docs'))
    p.add_argument('--cli-help', help='file with the output of `axiz <command> --help`, one section per command')
    a = p.parse_args()
    if not os.path.isdir(os.path.join(a.framework, 'codegen')):
        sys.exit(f'{a.framework} is not an axiz-framework checkout')
    modules = module_readmes(a.framework)
    _, archetypes = capabilities(a.framework, a.docs, modules)
    archetype_catalog(archetypes, a.docs)
    adrs(a.framework, a.docs)
    reference(modules, a.docs)
    if a.cli_help:
        cli_reference(a.cli_help, a.docs)
    print('reference pages generated in', os.path.normpath(a.docs))


if __name__ == '__main__':
    main()
